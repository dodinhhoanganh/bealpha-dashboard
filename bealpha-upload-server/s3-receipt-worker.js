const { S3Client, ListObjectsV2Command, GetObjectCommand, DeleteObjectCommand } = require("@aws-sdk/client-s3");
const { Pool } = require("pg");

// ── Guard: Skip entirely if S3 credentials are not configured ──
const awsKey = process.env.AWS_ACCESS_KEY_ID || "";
const awsSecret = process.env.AWS_SECRET_ACCESS_KEY || "";
const redisUrl = process.env.REDIS_URL || process.env.REDIS_URI || "";
const S3_CONFIGURED = awsKey && awsSecret && awsKey !== "mock-key" && awsSecret !== "mock-secret";

// Only require Redis if we actually need it
let redis = null;
if (S3_CONFIGURED && redisUrl) {
  try {
    const Redis = require("ioredis");
    redis = new Redis(redisUrl, {
      maxRetriesPerRequest: null,
      retryStrategy(times) {
        if (times > 3) return null;
        return Math.min(times * 2000, 10000);
      },
      lazyConnect: true,
    });
    redis.on("error", () => { /* swallow */ });
  } catch (e) {
    console.warn("[S3 Worker] Redis not available, proceeding without duplicate lock.");
  }
}

// Connect to PostgreSQL (Dashboard DB)
const pool = S3_CONFIGURED ? new Pool({ connectionString: process.env.DATABASE_URL }) : null;

// Configure Custom S3 Client
const s3Client = S3_CONFIGURED ? new S3Client({
  region: process.env.AWS_REGION || "us-east-1",
  endpoint: process.env.S3_ENDPOINT,
  credentials: {
    accessKeyId: awsKey,
    secretAccessKey: awsSecret,
  },
  forcePathStyle: true,
}) : null;

const BUCKET_NAME = process.env.RECEIPT_BUCKET_NAME || "bealpha-receipts";

async function streamToString(stream) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    stream.on("data", (chunk) => chunks.push(chunk));
    stream.on("error", reject);
    stream.on("end", () => resolve(Buffer.concat(chunks).toString("utf8")));
  });
}

/**
 * Polls the S3 bucket for XML/JSON receipt files generated by the custom upload system.
 */
async function pollReceipts() {
  if (!S3_CONFIGURED || !s3Client || !pool) return;

  try {
    const listCommand = new ListObjectsV2Command({
      Bucket: BUCKET_NAME,
      Prefix: "receipts/",
      MaxKeys: 50,
    });
    
    const { Contents } = await s3Client.send(listCommand);
    
    if (!Contents || Contents.length === 0) {
      return; // No receipts
    }

    for (const object of Contents) {
      if (!object.Key.endsWith(".xml") && !object.Key.endsWith(".json")) continue;

      // Prevent duplicate processing (skip if Redis unavailable)
      if (redis) {
        try {
          const lockKey = `receipt:lock:${object.Key}`;
          const locked = await redis.set(lockKey, "1", "NX", "EX", 3600);
          if (!locked) continue;
        } catch (e) {
          // Redis down — proceed without lock
        }
      }

      console.log(`[S3 Worker] Processing receipt: ${object.Key}`);

      try {
        const getCommand = new GetObjectCommand({
          Bucket: BUCKET_NAME,
          Key: object.Key,
        });
        
        const { Body } = await s3Client.send(getCommand);
        const receiptContent = await streamToString(Body);
        
        let releaseId = null;
        let status = "FAILED";
        
        if (object.Key.endsWith(".json")) {
          const data = JSON.parse(receiptContent);
          releaseId = data.releaseId || data.ReleaseId;
          status = data.status || data.Status;
        } else {
          const releaseIdMatch = receiptContent.match(/<ReleaseId>(.*?)<\/ReleaseId>/i);
          const statusMatch = receiptContent.match(/<Status>(.*?)<\/Status>/i);
          if (releaseIdMatch) releaseId = releaseIdMatch[1];
          if (statusMatch) status = statusMatch[1];
        }

        if (releaseId) {
          const deliveryStatus = status.toUpperCase() === "SUCCESS" ? "DELIVERED" : "FAILED";
          await pool.query(
            `UPDATE "DdexDelivery" SET status = $1, "updatedAt" = NOW() WHERE "batchId" = $2 OR "releaseId" = $2`,
            [deliveryStatus, releaseId]
          );
          console.log(`[S3 Worker] Updated delivery status for Release ${releaseId} to ${deliveryStatus}`);
        }

        const deleteCommand = new DeleteObjectCommand({
          Bucket: BUCKET_NAME,
          Key: object.Key,
        });
        await s3Client.send(deleteCommand);
        console.log(`[S3 Worker] Deleted processed receipt: ${object.Key}`);
        
      } catch (err) {
        console.error("[S3 Worker] Failed to process receipt %s: %s", object.Key, err.message);
        if (redis) {
          try { await redis.del(`receipt:lock:${object.Key}`); } catch (e) { /* ignore */ }
        }
      }
    }
  } catch (err) {
    if (err.name === "NoSuchBucket" || err.code === "ECONNREFUSED") {
      console.warn(`[S3 Worker] Bucket connection failed. Ensure S3 is configured correctly.`);
    } else {
      console.error("[S3 Worker] Polling error:", err.message);
    }
  }
}

function startS3Polling() {
  if (!S3_CONFIGURED) {
    console.log("[S3 Worker] Skipped — AWS credentials not configured (set AWS_ACCESS_KEY_ID & AWS_SECRET_ACCESS_KEY).");
    return;
  }
  setInterval(pollReceipts, 60 * 1000);
  console.log("[S3 Worker] Started S3 Receipt Polling...");
  setTimeout(pollReceipts, 5000);
}

module.exports = { startS3Polling };

