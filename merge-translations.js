const viPath = 'e:/bealpha/bealpha-dashboard/lib/i18n/vi.json';
const viData = JSON.parse(fs.readFileSync(viPath, 'utf8'));

let count = 0;
for (const [k, v] of Object.entries(translated)) {
    if (!viData[k]) {
        viData[k] = v;
        count++;
    }
}

// Write the file back with proper sorting
const sortedVi = Object.keys(viData).sort().reduce(
  (obj, key) => { 
    obj[key] = viData[key]; 
    return obj;
  }, 
  {}
);

fs.writeFileSync(viPath, JSON.stringify(sortedVi, null, 2), 'utf8');
console.log(`Merged ${count} translations into vi.json`);
